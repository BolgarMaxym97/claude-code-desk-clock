// Builds src/gen/scenes.js from the design artifact sources (design/idle-anim/src): the same scene code that
// drives the device animations, so the video shows them pixel for pixel.
import fs from 'node:fs';
import path from 'node:path';
const SRC = path.resolve(import.meta.dirname, '../../../design/idle-anim/src');
const read = (f) => fs.readFileSync(path.join(SRC, f), 'utf8');
const gen = read('gen.py');
const a = gen.indexOf("const CLAY = '#D97757'");
const b = gen.indexOf('__CELLS__');
const engine = gen.slice(a, b).replace('__FRAMES__', read('frames.js'));
let out = '/* generated by scripts/gen-scenes.mjs — do not edit */\n';
for (const [name, file] of [['pack', 'pack.js'], ['pack2', 'pack2.js'], ['pack3', 'pack3.js'], ['work', 'work.js'], ['reset', 'reset.js']]) {
  out += `export function ${name}(t) {\n${engine}\n${read(file)}\nreturn cells.map((c) => Object.assign(c, { px: px(c.frame, c.body), _px: px }));\n}\n`;
}
fs.mkdirSync(path.resolve(import.meta.dirname, '../src/gen'), { recursive: true });
fs.writeFileSync(path.resolve(import.meta.dirname, '../src/gen/scenes.js'), out);
console.log('scenes.js', out.length, 'bytes');
