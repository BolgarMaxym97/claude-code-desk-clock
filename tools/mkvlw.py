#!/usr/bin/env python3
"""Generate TFT_eSPI smooth fonts (.vlw format) as PROGMEM C arrays.

Usage: mkvlw.py <fonts_dir> <out_header>
Each entry: (C name, ttf file, px size, weight, charset).
"""
import struct
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ASCII = "".join(chr(c) for c in range(0x20, 0x7F))
UA = "АБВГҐДЕЄЖЗИІЇЙКЛМНОПРСТУФХЦЧШЩЬЮЯабвгґдеєжзиіїйклмнопрстуфхцчшщьюя’"
EXTRA = "·′…—«»°"
TEXT = ASCII + UA + EXTRA
DIGITS = "0123456789: "

FONTS = [
    ("F_TIME", "JBMono.ttf", 74, 700, DIGITS),
    ("F_TIME_S", "JBMono.ttf", 60, 700, DIGITS),
    ("F_BIG", "JBMono.ttf", 48, 800, DIGITS),
    ("F_H", "Inter.ttf", 24, 800, TEXT),
    ("F_S", "Inter.ttf", 15, 600, TEXT),
    ("F_S3", "Inter.ttf", 13, 500, TEXT),
    ("F_TOP", "Inter.ttf", 13, 700, TEXT),
    ("F_MONO", "JBMono.ttf", 15, 600, TEXT),
    ("F_LIM", "JBMono.ttf", 14, 700, TEXT),
]


def load(path: Path, size: int, weight: int) -> ImageFont.FreeTypeFont:
    font = ImageFont.truetype(str(path), size)
    axes = font.get_variation_axes()
    values = []
    for ax in axes:
        name = ax["name"]
        if name in (b"Weight", "Weight"):
            values.append(weight)
        elif name in (b"Optical size", "Optical size"):
            values.append(max(ax["minimum"], min(ax["maximum"], size)))
        else:
            values.append(ax["default"])
    if axes:
        font.set_variation_by_axes(values)
    return font


def has_glyph(font: ImageFont.FreeTypeFont, ch: str) -> bool:
    if ch == " ":
        return True
    return font.getmask(ch).getbbox() is not None


def build(font: ImageFont.FreeTypeFont, size: int, chars: str) -> bytes:
    chars = sorted({c for c in chars if has_glyph(font, c)}, key=ord)
    ascent, descent = font.getmetrics()
    meta, bitmaps = [], []
    for ch in chars:
        adv = round(font.getlength(ch))
        if ch == " ":
            meta.append((ord(ch), 0, 0, adv, 0, 0))
            continue
        x0, y0, x1, y1 = font.getbbox(ch, anchor="ls")
        w, h = x1 - x0, y1 - y0
        img = Image.new("L", (w, h), 0)
        ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255, anchor="ls")
        meta.append((ord(ch), h, w, adv, -y0, x0))
        bitmaps.append(img.tobytes())
    out = struct.pack(">6i", len(meta), 11, size, 0, ascent, descent)
    for (u, h, w, adv, dy, dx) in meta:
        out += struct.pack(">7i", u, h, w, adv, dy, dx, 0)
    return out + b"".join(bitmaps)


def main() -> None:
    fonts_dir, out = Path(sys.argv[1]), Path(sys.argv[2])
    lines = ["// Generated by tools/mkvlw.py - do not edit.", "#pragma once", "#include <pgmspace.h>", ""]
    for name, file, size, weight, chars in FONTS:
        data = build(load(fonts_dir / file, size, weight), size, chars)
        body = ",".join(str(b) for b in data)
        lines.append(f"// {file} {size}px w{weight}: {len(data)} bytes")
        lines.append(f"const uint8_t {name}[] PROGMEM = {{{body}}};")
        print(f"{name}: {len(data)} bytes")
    out.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
